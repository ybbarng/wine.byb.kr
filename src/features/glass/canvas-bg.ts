// 글라스 캔버스(3D 씬)의 배경색.
//
// 씬은 ACES 톤매핑을 거치므로, 캔버스에 `#9a8168` 을 주면 화면에는 `#bda588` 로 나온다.
// 그 `#bda588` 이 globals.css 의 `--background` 와 같은 값이라 캔버스 사각형이 보이지
// 않는다 — 잔이 슬라이드해도 배경은 가만히 있고 "잔"만 미끄러지는 것처럼 보이는 이유다.
//
// 페이지·프레임 쪽 배경에는 이 파일의 값을 쓰지 않는다. `bg-background` 를 쓴다 —
// 색의 단일 출처는 토큰이고, 여기 있는 건 그 색을 만들기 위한 **씬 입력값**이다.
// (예전엔 다섯 파일이 두 hex 를 각자 적어 두고 있었다.)

/** 캔버스에 넘기는 3D 씬 배경. 톤매핑 뒤 `CANVAS_TONEMAPPED` 로 보인다. */
export const CANVAS_BG = "#9a8168";

/**
 * 위 색이 톤매핑을 거쳐 화면에 나오는 값. `--background` 와 같아야 이음새가 없다.
 * `canvas-bg.test.ts` 가 globals.css 를 읽어 일치를 확인한다 — 토큰만 바꾸면 캔버스
 * 둘레에 색이 다른 사각형이 뜨는데, 눈에 잘 안 띄어 한참 뒤에야 알게 된다.
 */
export const CANVAS_TONEMAPPED = "#bda588";
