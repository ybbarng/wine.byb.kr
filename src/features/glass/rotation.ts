// 홈에서 잔을 갈아 끼우는 순서와 리듬.
//
// 화면이 저 혼자 움직이는 일은 **하나의 리듬**으로 묶는다. 스월과 교체를 따로 도는
// 타이머 두 개로 두면 둘이 겹치는 순간이 생기고, 그때가 제일 산만해 보인다.
// 그래서 "와인 한 잔이 들어와서 나갈 때까지"를 한 덩어리로 잡고 그 안에 스월을 둔다.
//
//   0초   잔이 옆에서 들어온다(1.3초 걸린다) → 거의 다 왔을 때 이름이 얹힌다
//   7초   스월 (auto-swirl.ts, FluidLab 이 알아서 돈다)
//   25초  스월 한 번 더
//   42초  이름이 먼저 나가고 잔이 뒤따라 나간다 → 다음 와인
//
// 네 번에 한 번은 그 사이(잔은 들어왔는데 이름은 아직인 틈)에 건배말이 끼어든다.
// 새 사건을 만들지 않고 이미 비어 있는 자리와 시간을 쓰는 것이다 — 화면이 움직이는
// 횟수는 그대로고, 틈만 1.45초에서 2.55초로 늘어난다.
//
// 숫자는 느린 쪽에서 시작했다. 빠른 걸 늦추는 건 쉬워도 이미 산만하다고 느낀 인상은
// 잘 안 지워진다.

/** 와인 한 잔이 머무는 시간(초). */
export const WINE_HOLD_S = 42;

/** 잔이 나가기 얼마 전에 이름이 먼저 빠지는지(초). 이름 → 잔 순서로 나간다. */
export const NAME_LEAD_S = 0.35;

/**
 * 잔이 들어오기 시작한 뒤 이름이 따라 들어오기까지(초).
 *
 * 잔의 교차 슬라이드가 1.3초다(FluidLab 의 `slideDur`). 그보다 훨씬 일찍 띄우면 잔이
 * 아직 화면 가장자리에 있는데 이름만 먼저 자리를 잡아, 둘이 따로 노는 것처럼 보인다.
 * 잔이 거의 다 들어왔을 때 이름이 얹히도록 맞춘다 — 눈이 잔에서 이름으로 옮겨 간다.
 */
export const NAME_DELAY_S = 1.1;

/**
 * 잔을 만진 뒤 순환을 다시 시작하기까지 기다리는 시간(초).
 *
 * 사용자가 잔을 붙잡고 돌리는 중에 잔이 슬라이드아웃되면 최악이다. 만지는 동안은
 * 물론이고, 손을 뗀 뒤로도 한동안은 그대로 둔다 — 방금 만진 잔을 더 보고 싶을 수 있다.
 */
export const RESUME_AFTER_TOUCH_S = 15;

/**
 * 이름·건배말이 미끄러져 들어오고 나가는 데 걸리는 시간(ms).
 *
 * 컴포넌트가 아니라 여기 있다 — 아래 시간표가 이 값에 기대고 있어서, 컴포넌트에 두면
 * 그 값을 늘렸을 때 건배말과 이름이 한 자리에서 겹치는데도 테스트가 통과한다.
 */
export const NAME_MOVE_MS = 420;

/**
 * 몇 번째 교체마다 건배말을 한 번 띄우는지.
 *
 * 매번 띄우면 이름이 늘 늦게 오고, 화면이 말을 너무 많이 한다. 4번마다면 42초 × 4 =
 * 3분에 한 번꼴이라 "가끔 인사한다" 쪽에 가깝다. 첫 교체는 자연히 빠진다 — 홈에 막
 * 들어온 사람은 이름부터 봐야 한다.
 */
export const TOAST_EVERY = 4;

/** 잔이 밀리기 시작하고 건배말이 뜨기까지(초). 잔이 들어오는 동안 함께 보이게. */
export const TOAST_DELAY_S = 0.25;

/** 건배말이 다시 빠지기 시작하는 시각(초, 잔이 밀리기 시작한 때 기준). */
export const TOAST_EXIT_S = 1.75;

/**
 * 건배말이 있는 회차의 이름 등장 시각(초). 보통은 `NAME_DELAY_S`.
 *
 * 건배말이 다 빠진 뒤에 이름이 들어와야 한 자리에서 둘이 겹치지 않는다 —
 * `TOAST_EXIT_S` + 빠지는 시간(0.42초)보다 뒤여야 한다.
 */
export const TOAST_NAME_DELAY_S = 2.2;

/**
 * 이번이 건배말을 띄울 차례인가. `i` 는 순환 순서에서 지금 와인의 자리(0부터).
 *
 * 무작위로 정하지 않는다 — 운 나쁘면 두 번 연달아 나오고, 그게 제일 산만하다.
 */
export function isToastTurn(i: number): boolean {
  return i >= 0 && (i + 1) % TOAST_EVERY === 0;
}

/**
 * 순환 순서를 만든다. 무작위로 매번 뽑지 않고 **한 번 섞어 차례로** 꺼낸다.
 *
 * 매번 무작위로 뽑으면 같은 와인이 연달아 나오는 일이 생각보다 자주 생기고(60종이라도
 * 체감으로는 자주 겹친다), 한 바퀴 도는 동안 아예 안 나오는 와인도 생긴다.
 *
 * 어디까지 왔는지는 셸이 `homeIndex` 로 들고 있다 — 상세를 다녀와도 그 자리에서
 * 이어지므로 여기서 특정 와인을 앞으로 끌어올 필요가 없다.
 */
export function rotationOrder<T extends { slug: string }>(
  wines: readonly T[],
  random: () => number = Math.random
): T[] {
  const out = [...wines];
  // Fisher–Yates.
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
