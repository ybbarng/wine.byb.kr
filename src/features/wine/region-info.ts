export function countryInfo(ko: string | null | undefined): string | null {
  if (!ko) return null;
  return COUNTRY_INFO[ko.trim()] ?? null;
}

/** 와인의 지역 문자열에 포함된 산지를 찾아 그 설명을 돌려준다. */
export function regionInfo(
  regionName: string | null | undefined
): { name: string; desc: string } | null {
  if (!regionName) return null;
  for (const [name, desc] of Object.entries(REGION_INFO)) {
    if (regionName.includes(name)) return { name, desc };
  }
  return null;
}
