export function countryInfo(ko: string | null | undefined): string | null {
  if (!ko) return null;
  return COUNTRY_INFO[ko.trim()] ?? null;
}

/** 와인의 지역 문자열에 포함된 산지를 찾아 그 정보를 돌려준다. */
export function regionInfo(
  regionName: string | null | undefined
): (RegionDetail & { name: string }) | null {
  if (!regionName) return null;
  for (const [name, detail] of Object.entries(REGION_INFO)) {
    if (regionName.includes(name)) return { name, ...detail };
  }
  return null;
}
