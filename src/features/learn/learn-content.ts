export type Block =
  | { type: "text"; heading?: string; body: string }
  | { type: "callout"; emoji?: string; body: string }
  | { type: "table"; heading?: string; head: string[]; rows: string[][] }
  | { type: "cards"; heading?: string; items: { title: string; tag?: string; body: string }[] }
