export type Block =
  | { type: "text"; heading?: string; body: string }
  | { type: "callout"; emoji?: string; body: string }
  | { type: "table"; heading?: string; head: string[]; rows: string[][] }
  | { type: "cards"; heading?: string; items: { title: string; tag?: string; body: string }[] }
  // level은 1~5. 여러 항목의 세기를 막대로 비교한다.
  | { type: "scale"; heading?: string; items: { label: string; level: number; note?: string }[] }
  // pos는 0~1. 축 위에 항목을 배치해 스펙트럼을 보여준다.
  | {
      type: "spectrum";
      heading?: string;
      leftLabel: string;
      rightLabel: string;
      items: { label: string; pos: number }[];
    };

export interface LessonLink {
  label: string;
  href: string;
}

export interface Lesson {
  slug: string;
  emoji: string;
  title: string;
  summary: string;
  blocks: Block[];
  links?: LessonLink[];
}

