async function main() {
  let updated = 0;
  const missing: string[] = [];
  for (const [slug, notesKo] of Object.entries(NOTES)) {
    const w = await db.wine.findUnique({ where: { slug }, select: { id: true } });
    if (!w) {
      missing.push(slug);
      continue;
    }
    await db.wine.update({ where: { slug }, data: { notesKo } });
    updated++;
  }
  console.log(`시음 포인트 ${updated}건 반영.`);
  if (missing.length > 0) {
    console.warn(`와인 없음 ${missing.length}건(스킵): ${missing.join(", ")}`);
  }
  await db.$disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
